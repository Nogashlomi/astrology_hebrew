#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
STEP 6 - Build the visualizer HTML tool from the manuscripts, metadata and images.

Input:  code/visualizer_template/ (index.html, app.js, style.css)
        data/metadata/clean/visualizer_data.json     (step 3)
        data/illustrations/illustrations.csv         (step 4, optional)
        data/clusters/clusters.json                  (step 5, optional)
Output: visualizer/  - open visualizer/index.html in a browser.
        Page images are linked from data/manuscripts/ (not copied), so keep visualizer/ next to data/.

Illustrations and clusters are added to window.SPHAERA_DATA when present. (The variable keeps the name it had
in the Hebrew Sacrobosco project, whose visualizer this one is copied from.)

Usage:  python code/06_build_visualizer.py
"""
import json
import re
import shutil
import time

import pandas as pd

from paths import PROJECT_ROOT, CLEAN_METADATA_DIR, ILLUSTRATIONS_DIR, CLUSTERS_DIR, \
    VISUALIZER_TEMPLATE_DIR, VISUALIZER_DIR


def main():
    data = json.loads((CLEAN_METADATA_DIR / "visualizer_data.json").read_text(encoding="utf-8"))

    ill_csv = ILLUSTRATIONS_DIR / "illustrations.csv"
    data["illustrations"] = pd.read_csv(ill_csv, dtype=str).fillna("").to_dict("records") if ill_csv.exists() else []

    clusters_json = CLUSTERS_DIR / "clusters.json"
    data["clusters"] = json.loads(clusters_json.read_text(encoding="utf-8")) if clusters_json.exists() else None

    # each group's most typical crop (smallest distance to the group centre) is its example picture
    clusters_csv = CLUSTERS_DIR / "clusters.csv"
    if data["clusters"] and clusters_csv.exists():
        distance = pd.read_csv(clusters_csv, dtype={"illustration_id": str}).set_index("illustration_id")["distance"]
        for c in data["clusters"]["clusters"]:
            ids = [i for i in c["illustration_ids"] if i in distance.index]
            c["example_id"] = min(ids, key=lambda i: distance[i]) if ids else (c["illustration_ids"] or [""])[0]

    VISUALIZER_DIR.mkdir(parents=True, exist_ok=True)
    for f in VISUALIZER_TEMPLATE_DIR.iterdir():
        if f.is_file():
            shutil.copy2(f, VISUALIZER_DIR / f.name)

    # stamp script/style links (app.js?v=...) with the build time so browsers never show a stale copy
    index_html = VISUALIZER_DIR / "index.html"
    build = time.strftime("%Y%m%d%H%M%S")
    index_html.write_text(re.sub(r"\.(js|css)\?v=\w+", rf".\1?v={build}", index_html.read_text(encoding="utf-8")),
                          encoding="utf-8")

    data_js = VISUALIZER_DIR / "data.js"
    with data_js.open("w", encoding="utf-8") as f:
        f.write("// Hebrew Astrological Manuscripts 1250-1450 Data Store (generated by code/06_build_visualizer.py)\n")
        f.write("window.SPHAERA_DATA = ")
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"Built {VISUALIZER_DIR.relative_to(PROJECT_ROOT)}/index.html "
          f"({len(data['manuscripts'])} manuscripts, {len(data['illustrations'])} illustrations, "
          f"{'with' if data['clusters'] else 'no'} clusters)")


if __name__ == "__main__":
    main()
